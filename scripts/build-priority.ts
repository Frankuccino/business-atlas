/** Parse the catalog's domain tables into id -> priority. */
function parseCatalog(): Map<string, Priority> {
  const text = readFileSync(CATALOG, 'utf8');
  const map = new Map<string, Priority>();

  // Rows look like: | cogs | Cost of Goods Sold | term | 1 | P1 | done |
  // The id is the first cell, priority the fifth. Anchoring on the pipe-delimited
  // shape rather than a loose regex keeps a title containing "P1" from matching.
  const row = /^\|\s*([a-z0-9-]+)\s*\|[^|]*\|[^|]*\|[^|]*\|\s*(P[123])\s*\|/;

  for (const line of text.split('\n')) {
    const match = row.exec(line);
    // noUncheckedIndexedAccess makes capture groups `string | undefined`, so
    // both have to be narrowed before the map sees them.
    const id = match?.[1];
    const priority = match?.[2];
    if (id && priority) {
      map.set(id, priority as Priority);
    }
  }

  return map;
}

function main(): void {
  const priorityByEntry = parseCatalog();

  if (priorityByEntry.size === 0) {
    throw new Error(`No priority rows parsed from ${CATALOG}`);
  }

  const counts = PRIORITIES.map(
    (p) => `${p}: ${[...priorityByEntry.values()].filter((v) => v === p).length}`,
  ).join(', ');

  const lines = [
    '/**',
    ' * GENERATED by scripts/build-priority.ts. Do not edit by hand.',
    ' *',
    ' * Priority lives in docs/catalog.md and nowhere else. This module is the',
    ' * web\'s view of that column, so the two cannot drift.',
    ' *',
    ` * Last generated: ${counts}`,
    ' */',
    '',
    "export type Priority = 'P1' | 'P2' | 'P3';",
    '',
    'export interface Phase {',
    '  id: Priority;',
    '  name: string;',
    '  title: string;',
    '  description: string;',
    '  /** Mastery fraction a user must reach before this phase unlocks. */',
    '  unlockAt: number;',
    '}',
    '',
    'export const PHASES: Phase[] = ' + JSON.stringify(PHASES, null, 2) + ';',
    '',
    'export interface LayerMeta {',
    '  n: Layer;',
    '  name: string;',
    '  description: string;',
    '}',
    '',
    "export type Layer = 1 | 2 | 3 | 4;",
    '',
    'export const LAYERS: LayerMeta[] = ' + JSON.stringify(LAYER_META, null, 2) + ';',
    '',
    '/** Entry id -> priority band. */',
    'export const PRIORITY_BY_ENTRY: Record<string, Priority> = ' +
      JSON.stringify(Object.fromEntries(priorityByEntry), null, 2) +
      ';',
    '',
    '/** The phase an entry belongs to, or P1 when the catalog has no row. */',
    'export function phaseOf(entryId: string): Priority {',
    '  return PRIORITY_BY_ENTRY[entryId] ?? "P1";',
    '}',
    '',
    '/** Entry ids in one phase, sorted. */',
    'export function entriesInPhase(phase: Priority): string[] {',
    '  return Object.entries(PRIORITY_BY_ENTRY)',
    '    .filter(([, p]) => p === phase)',
    '    .map(([id]) => id)',
    '    .sort();',
    '}',
    '',
    '/** How many entries each phase holds. */',
    'export function phaseSize(phase: Priority): number {',
    '  return entriesInPhase(phase).length;',
    '}',
    '',
  ];

  mkdirSync(join(OUT, '..'), { recursive: true });
  writeFileSync(OUT, lines.join('\n'));

  console.log(`priority map written: ${priorityByEntry.size} entries (${counts})`);
}

main();
